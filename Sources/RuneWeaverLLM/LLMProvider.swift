/// A function-style tool description sent to the model.
///
/// ``ToolDefinition`` is the provider-layer view of a
/// ``Tool``: the name, human-readable description, and JSON Schema
/// the model uses to decide when and how to call it. It mirrors the
/// OpenAI `function` object so every OpenAI-compatible backend
/// (MLX, llama.cpp, OpenRouter, custom endpoints) shares one shape.
public struct ToolDefinition: Sendable, Codable, Equatable {
    /// Stable machine-readable identifier (e.g. `"email.search"`).
    public let name: String
    /// Human- and LLM-readable summary of when to use this tool.
    public let description: String
    /// JSON Schema describing the expected input arguments.
    public let parameters: JSONSchema

    /// Creates a tool definition.
    /// - Parameters:
    ///   - name: Stable tool identifier.
    ///   - description: Summary of when to use this tool.
    ///   - parameters: JSON Schema for the arguments.
    public init(name: String, description: String, parameters: JSONSchema) {
        self.name = name
        self.description = description
        self.parameters = parameters
    }

    /// Creates a definition from a runtime tool plugin.
    /// - Parameter tool: The registered tool.
    public init(_ tool: any Tool) {
        self.name = tool.name
        self.description = tool.description
        self.parameters = tool.inputSchema
    }
}

/// A single model-requested tool invocation.
public struct ToolCall: Sendable, Codable, Equatable {
    /// Identifier correlating this call with its result.
    public let id: String
    /// Name of the tool being invoked.
    public let name: String
    /// Raw JSON arguments matching the tool's schema.
    public let argumentsJSON: String

    /// Creates a tool call.
    /// - Parameters:
    ///   - id: Correlation identifier.
    ///   - name: Tool name.
    ///   - argumentsJSON: Raw JSON arguments.
    public init(id: String, name: String, argumentsJSON: String) {
        self.id = id
        self.name = name
        self.argumentsJSON = argumentsJSON
    }
}

/// Token accounting for one completed response.
public struct TokenUsage: Sendable, Codable, Equatable {
    /// Tokens in the request (prompt + tools + history).
    public let promptTokens: Int
    /// Tokens generated by the model.
    public let completionTokens: Int
    /// Total tokens billed for the request.
    public let totalTokens: Int

    /// Creates token usage.
    /// - Parameters:
    ///   - promptTokens: Request tokens.
    ///   - completionTokens: Generated tokens.
    ///   - totalTokens: Total tokens.
    public init(promptTokens: Int, completionTokens: Int, totalTokens: Int) {
        self.promptTokens = promptTokens
        self.completionTokens = completionTokens
        self.totalTokens = totalTokens
    }
}

/// Metadata delivered with the terminal chunk of a response.
public struct ResponseMetadata: Sendable, Codable, Equatable {
    /// Model that served the response, as reported by the server.
    public let model: String
    /// Token accounting, when the server reports it.
    public let usage: TokenUsage?
    /// Stop reason (`"stop"`, `"tool_calls"`, `"length"`, ...).
    public let finishReason: String?

    /// Creates response metadata.
    /// - Parameters:
    ///   - model: Serving model name.
    ///   - usage: Token accounting, if reported.
    ///   - finishReason: Stop reason, if reported.
    public init(model: String, usage: TokenUsage? = nil, finishReason: String? = nil) {
        self.model = model
        self.usage = usage
        self.finishReason = finishReason
    }
}

/// One streamed event from a chat completion.
///
/// Providers that speak OpenAI-compatible SSE map each server event to
/// one of these cases. The router-facing ``LLMResponse`` stream carries
/// text only; consumers that need tool calls or usage should consume
/// ``ChunkStreamingProvider/chatChunks(messages:tools:)`` directly.
public enum LLMResponseChunk: Sendable, Equatable {
    /// Incremental model text.
    case textDelta(String)
    /// A fully reassembled model-requested tool invocation.
    case toolCall(ToolCall)
    /// The response is complete.
    case done(ResponseMetadata)
    /// The request failed mid-stream. The stream ends after this chunk.
    case error(String)
}

/// Failures raised by the OpenAI-compatible provider stack.
public enum LLMProviderError: Error, Sendable, Equatable {
    /// The server could not be reached or returned a transport error.
    case unavailable(String)
    /// The server answered with a non-2xx status.
    /// - Parameters:
    ///   - statusCode: HTTP status code.
    ///   - message: Server-provided detail, if any.
    case requestFailed(statusCode: Int, message: String)
    /// The server answered with bytes that could not be decoded.
    case invalidResponse(String)
    /// Streaming terminated unexpectedly.
    case streamingFailed(String)
    /// This backend has no usable embeddings endpoint.
    case embeddingsUnsupported(String)
}

// MARK: - Provider conveniences

public extension LLMProvider {
    /// Stable provider identifier. Defaults to the active model's
    /// `provider` field; concrete providers override with a constant.
    var name: String {
        modelInfo.provider
    }

    /// Whether the backend answers health checks right now.
    ///
    /// The default implementation optimistically returns `true`.
    /// Concrete providers override this with a lightweight
    /// `GET <base>/models` probe that never throws.
    func isAvailable() async -> Bool {
        true
    }

    /// Maps runtime tool plugins to provider-layer definitions.
    /// - Parameter tools: Registered tools the model may call.
    /// - Returns: Definitions in provider wire shape.
    func toolDefinitions(for tools: [any Tool]) -> [ToolDefinition] {
        tools.map { ToolDefinition($0) }
    }
}

/// An ``LLMProvider`` that natively streams ``LLMResponseChunk`` events.
///
/// The chunk stream is the primary provider API: it preserves tool
/// calls, usage, and errors that the text-only ``LLMResponse`` stream
/// cannot represent. The default ``chat(messages:tools:)``
/// implementation maps chunks to text so the ``LLMRouter`` keeps
/// working unchanged.
public protocol ChunkStreamingProvider: LLMProvider {
    /// Streams chunk-level events for the given history and tools.
    /// - Parameters:
    ///   - messages: Conversation history.
    ///   - tools: Tool definitions the model may call.
    /// - Returns: Stream of response chunks, ending in `done` or `error`.
    func chatChunks(messages: [Message], tools: [ToolDefinition]) -> AsyncStream<LLMResponseChunk>
}

public extension ChunkStreamingProvider {
    /// Streams text via ``chatChunks(messages:tools:)``.
    ///
    /// Text deltas yield ``LLMResponse`` deltas verbatim. Tool calls
    /// have no text representation and are skipped here; consume
    /// ``chatChunks(messages:tools:)`` to observe them. Transport
    /// `.error` chunks terminate the stream empty (they are never
    /// surfaced as assistant text) so failures cannot leak into
    /// conversation history; the stream always terminates with an
    /// `isFinished` chunk.
    /// - Parameters:
    ///   - messages: Conversation history.
    ///   - tools: Tools the model may call.
    /// - Returns: Stream of text response chunks.
    func chat(messages: [Message], tools: [any Tool]) -> AsyncStream<LLMResponse> {
        let definitions = toolDefinitions(for: tools)
        let chunks = chatChunks(messages: messages, tools: definitions)
        return AsyncStream { continuation in
            let task = Task {
                chunkLoop: for await chunk in chunks {
                    switch chunk {
                    case let .textDelta(text):
                        continuation.yield(LLMResponse(delta: text))
                    case .toolCall:
                        continue
                    case .done:
                        continuation.yield(LLMResponse(delta: "", isFinished: true))
                        break chunkLoop
                    case .error:
                        continuation.yield(LLMResponse(delta: "", isFinished: true))
                        break chunkLoop
                    }
                }
                continuation.finish()
            }
            continuation.onTermination = { @Sendable _ in task.cancel() }
        }
    }
}

// MARK: - Shared OpenAI-compatible HTTP plumbing (internal)

/// Role names used on the OpenAI-compatible wire.
enum OpenAIWireRole {
    /// Maps a core message role to its wire string.
    /// - Parameter role: Core conversation role.
    /// - Returns: Wire role string.
    static func string(for role: Message.Role) -> String {
        switch role {
        case .system: "system"
        case .user: "user"
        case .assistant: "assistant"
        case .tool: "tool"
        }
    }
}

/// Normalizes a configured server URL to its `/v1` API root.
/// - Parameter raw: Configured URL, with or without a `/v1` suffix.
/// - Returns: Base URL without a trailing slash, ending in `/v1`.
func openAIBaseURL(from raw: String) -> String {
    var trimmed = raw
    while trimmed.hasSuffix("/") {
        trimmed.removeLast()
    }
    if trimmed.hasSuffix("/v1") {
        return trimmed
    }
    return trimmed + "/v1"
}

/// Builds a JSON request body for `/chat/completions`.
/// - Parameters:
///   - model: Model identifier.
///   - messages: Conversation history.
///   - tools: Tool definitions, omitted when empty.
///   - stream: Whether to request server-sent events.
/// - Returns: JSON-encoded request body.
/// - Throws: ``LLMProviderError/invalidResponse(_:)`` when a tool
///   schema is not valid JSON or the body cannot be encoded.
func openAIChatRequestBody(
    model: String,
    messages: [Message],
    tools: [ToolDefinition],
    stream: Bool
) throws -> Data {
    var wireMessages: [[String: Any]] = messages.map { message in
        var entry: [String: Any] = [
            "role": OpenAIWireRole.string(for: message.role),
            "content": message.content
        ]
        if let callID = message.toolCallID {
            entry["tool_call_id"] = callID
        }
        return entry
    }
    if wireMessages.isEmpty {
        wireMessages = [["role": "user", "content": ""]]
    }
    var body: [String: Any] = [
        "model": model,
        "messages": wireMessages,
        "stream": stream
    ]
    if stream {
        body["stream_options"] = ["include_usage": true]
    }
    if !tools.isEmpty {
        body["tools"] = try tools.map { tool -> [String: Any] in
            guard let data = tool.parameters.rawValue.data(using: .utf8),
                  let parsed = try? JSONSerialization.jsonObject(with: data),
                  parsed is [String: Any]
            else {
                throw LLMProviderError.invalidResponse(
                    "Tool '\(tool.name)' has an invalid JSON Schema; expected a JSON object"
                )
            }
            return [
                "type": "function",
                "function": [
                    "name": tool.name,
                    "description": tool.description,
                    "parameters": parsed
                ]
            ]
        }
        body["tool_choice"] = "auto"
    }
    do {
        return try JSONSerialization.data(withJSONObject: body)
    } catch {
        throw LLMProviderError.invalidResponse("Could not encode chat request: \(error.localizedDescription)")
    }
}

/// Usage block reported inside streaming chunks.
struct OpenAIUsageDTO: Decodable, Sendable {
    /// Request tokens.
    var promptTokens: Int?
    /// Generated tokens.
    var completionTokens: Int?
    /// Total tokens.
    var totalTokens: Int?

    private enum CodingKeys: String, CodingKey {
        case promptTokens = "prompt_tokens"
        case completionTokens = "completion_tokens"
        case totalTokens = "total_tokens"
    }
}

/// One function-call delta inside a streamed tool call.
struct OpenAIFunctionDeltaDTO: Decodable, Sendable {
    /// Tool name fragment (present on the first delta).
    var name: String?
    /// Arguments JSON fragment.
    var arguments: String?
}

/// One streamed tool-call delta.
struct OpenAIToolCallDeltaDTO: Decodable, Sendable {
    /// Zero-based position of this call.
    var index: Int?
    /// Server-assigned call identifier.
    var id: String?
    /// Delta for the invoked function.
    var function: OpenAIFunctionDeltaDTO?
}

/// Message delta inside a streamed choice. `message` covers
/// non-streaming completions that arrive as a single JSON body.
struct OpenAIDeltaDTO: Decodable, Sendable {
    /// Incremental text.
    var content: String?
    /// Tool-call deltas requested by the model.
    var toolCalls: [OpenAIToolCallDeltaDTO]?

    private enum CodingKeys: String, CodingKey {
        case content
        case toolCalls = "tool_calls"
    }
}

/// One choice inside a streamed chunk.
struct OpenAIStreamChoiceDTO: Decodable, Sendable {
    /// Incremental delta (streaming) or full message (non-streaming).
    var delta: OpenAIDeltaDTO?
    /// Full message for non-streamed completions.
    var message: OpenAIDeltaDTO?
    /// Stop reason for the final chunk.
    var finishReason: String?

    private enum CodingKeys: String, CodingKey {
        case delta
        case message
        case finishReason = "finish_reason"
    }
}

/// One server-sent event payload.
struct OpenAIStreamChunkDTO: Decodable, Sendable {
    /// Serving model name.
    var model: String?
    /// Choices (exactly one in practice).
    var choices: [OpenAIStreamChoiceDTO]?
    /// Usage, usually on the final chunk when requested.
    var usage: OpenAIUsageDTO?
}

/// One embedding vector in an embeddings response.
struct OpenAIEmbeddingDTO: Decodable, Sendable {
    /// Embedding vector.
    var embedding: [Float]
    /// Position of the input text.
    var index: Int
}

/// Response body for `/embeddings`.
struct OpenAIEmbeddingsResponseDTO: Decodable, Sendable {
    /// One entry per input text.
    var data: [OpenAIEmbeddingDTO]
}

/// Accumulates streamed tool-call fragments into whole calls.
struct OpenAIToolCallAccumulator: Sendable {
    /// Buffered state per tool-call index.
    var buffers: [Int: Buffer] = [:]

    /// Buffered fragments for one tool call.
    struct Buffer: Sendable {
        /// Server-assigned call identifier.
        var id: String = ""
        /// Tool name.
        var name: String = ""
        /// Concatenated arguments JSON.
        var arguments: String = ""
    }

    /// Applies one streamed delta.
    /// - Parameter delta: Tool-call delta from the server.
    mutating func apply(_ delta: OpenAIToolCallDeltaDTO) {
        let index = delta.index ?? 0
        var buffer = buffers[index] ?? Buffer()
        if let id = delta.id, !id.isEmpty {
            buffer.id = id
        }
        if let name = delta.function?.name, !name.isEmpty {
            buffer.name += name
        }
        if let arguments = delta.function?.arguments {
            buffer.arguments += arguments
        }
        buffers[index] = buffer
    }

    /// Finished calls ordered by index, dropping empties.
    /// - Returns: Reassembled tool calls.
    func finishedCalls() -> [ToolCall] {
        buffers
            .sorted { $0.key < $1.key }
            .map { entry in
                ToolCall(
                    id: entry.value.id.isEmpty ? "call_\(entry.key)" : entry.value.id,
                    name: entry.value.name,
                    argumentsJSON: entry.value.arguments.isEmpty ? "{}" : entry.value.arguments
                )
            }
            .filter { !$0.name.isEmpty }
    }
}

/// Minimal shared client for OpenAI-compatible backends.
///
/// All three bundled providers (MLX, llama.cpp, generic cloud) speak
/// this protocol; the client centralizes request building, SSE
/// parsing, and embeddings decoding so providers stay thin.
struct OpenAICompatibleHTTPClient: Sendable {
    /// API root ending in `/v1` (no trailing slash).
    let baseURL: String
    /// Bearer token, if the endpoint requires auth.
    let apiKey: String?
    /// Model identifier sent with every request.
    let model: String

    /// Creates a client.
    /// - Parameters:
    ///   - baseURL: Server URL with or without `/v1`.
    ///   - apiKey: Bearer token, if required.
    ///   - model: Model identifier.
    init(baseURL: String, apiKey: String? = nil, model: String) {
        self.baseURL = openAIBaseURL(from: baseURL)
        self.apiKey = apiKey
        self.model = model
    }

    /// Builds an authorized JSON request.
    /// - Parameters:
    ///   - path: Path relative to the API root (e.g. `/chat/completions`).
    ///   - body: JSON-encoded body.
    ///   - timeout: Request timeout in seconds.
    /// - Returns: Configured URL request, or nil for a malformed URL.
    func makeRequest(path: String, body: Data, timeout: TimeInterval = 120) -> URLRequest? {
        guard let url = URL(string: baseURL + path) else { return nil }
        var request = URLRequest(url: url, timeoutInterval: timeout)
        request.httpMethod = "POST"
        request.setValue("application/json", forHTTPHeaderField: "Content-Type")
        if let apiKey, !apiKey.isEmpty {
            request.setValue("Bearer \(apiKey)", forHTTPHeaderField: "Authorization")
        }
        request.httpBody = body
        return request
    }

    /// Streams chat chunks for the given history and tools.
    /// - Parameters:
    ///   - messages: Conversation history.
    ///   - tools: Tool definitions the model may call.
    /// - Returns: Chunk stream ending in `done` or `error`.
    func streamChunks(messages: [Message], tools: [ToolDefinition]) -> AsyncStream<LLMResponseChunk> {
        let body: Data
        do {
            body = try openAIChatRequestBody(model: model, messages: messages, tools: tools, stream: true)
        } catch {
            let message: String = if let providerError = error as? LLMProviderError, case let .invalidResponse(detail) = providerError {
                detail
            } else {
                error.localizedDescription
            }
            return AsyncStream { continuation in
                continuation.yield(.error(message))
                continuation.finish()
            }
        }
        guard let request = makeRequest(path: "/chat/completions", body: body) else {
            return AsyncStream { continuation in
                continuation.yield(.error("Malformed chat URL: \(baseURL)"))
                continuation.finish()
            }
        }
        let clientModel = model
        return AsyncStream { continuation in
            let task = Task {
                do {
                    let (bytes, response) = try await URLSession.shared.bytes(for: request)
                    guard let http = response as? HTTPURLResponse else {
                        continuation.yield(.error("No HTTP response from \(self.baseURL)"))
                        continuation.finish()
                        return
                    }
                    guard (200 ..< 300).contains(http.statusCode) else {
                        let detail = await OpenAICompatibleHTTPClient.responseDetail(from: bytes)
                        continuation.yield(.error("Chat request failed (\(http.statusCode)): \(detail)"))
                        continuation.finish()
                        return
                    }
                    await OpenAICompatibleHTTPClient.pumpSSE(
                        bytes: bytes,
                        fallbackModel: clientModel,
                        continuation: continuation
                    )
                } catch is CancellationError {
                    continuation.finish()
                } catch {
                    continuation.yield(.error("Chat stream failed: \(error.localizedDescription)"))
                    continuation.finish()
                }
            }
            continuation.onTermination = { @Sendable _ in task.cancel() }
        }
    }

    /// Requests embeddings for the given texts.
    /// - Parameter texts: Texts to embed.
    /// - Returns: One vector per input text, in order.
    func requestEmbeddings(texts: [String]) async throws -> [[Float]] {
        let payload: [String: Any] = ["model": model, "input": texts]
        let body = (try? JSONSerialization.data(withJSONObject: payload)) ?? Data()
        guard let request = makeRequest(path: "/embeddings", body: body, timeout: 60) else {
            throw LLMProviderError.invalidResponse("Malformed embeddings URL: \(baseURL)")
        }
        let (data, response): (Data, URLResponse)
        do {
            (data, response) = try await URLSession.shared.data(for: request)
        } catch {
            throw LLMProviderError.unavailable("Embeddings request failed: \(error.localizedDescription)")
        }
        guard let http = response as? HTTPURLResponse else {
            throw LLMProviderError.invalidResponse("No HTTP response from \(baseURL)")
        }
        guard (200 ..< 300).contains(http.statusCode) else {
            let detail = String(data: data, encoding: .utf8) ?? ""
            if http.statusCode == 404 {
                throw LLMProviderError.embeddingsUnsupported("No embeddings endpoint at \(baseURL): \(detail)")
            }
            throw LLMProviderError.requestFailed(statusCode: http.statusCode, message: detail)
        }
        do {
            let decoded = try JSONDecoder().decode(OpenAIEmbeddingsResponseDTO.self, from: data)
            return decoded.data.sorted { $0.index < $1.index }.map(\.embedding)
        } catch {
            throw LLMProviderError.invalidResponse("Could not decode embeddings: \(error.localizedDescription)")
        }
    }

    /// Probes `GET <base>/models` without throwing.
    /// - Returns: True when the server answers with 2xx.
    func ping() async -> Bool {
        guard let url = URL(string: baseURL + "/models") else { return false }
        var request = URLRequest(url: url, timeoutInterval: 3)
        request.httpMethod = "GET"
        if let apiKey, !apiKey.isEmpty {
            request.setValue("Bearer \(apiKey)", forHTTPHeaderField: "Authorization")
        }
        do {
            let (_, response) = try await URLSession.shared.data(for: request)
            guard let http = response as? HTTPURLResponse else { return false }
            return (200 ..< 300).contains(http.statusCode)
        } catch {
            return false
        }
    }

    /// Reads a short error preview from an errored byte stream.
    /// - Parameter bytes: Response byte stream.
    /// - Returns: Decoded preview, or a placeholder.
    private static func responseDetail(from bytes: URLSession.AsyncBytes) async -> String {
        var preview = ""
        do {
            for try await line in bytes.lines {
                preview += line
                if preview.count > 500 {
                    break
                }
            }
        } catch {
            return "unreadable error body"
        }
        let trimmed = preview.trimmingCharacters(in: .whitespacesAndNewlines)
        return trimmed.isEmpty ? "empty error body" : String(trimmed.prefix(500))
    }

    /// Pumps SSE lines into chunk events.
    /// - Parameters:
    ///   - bytes: Response byte stream.
    ///   - fallbackModel: Model name when the server omits it.
    ///   - continuation: Stream continuation to feed.
    private static func pumpSSE(
        bytes: URLSession.AsyncBytes,
        fallbackModel: String,
        continuation: AsyncStream<LLMResponseChunk>.Continuation
    ) async {
        var accumulator = OpenAIToolCallAccumulator()
        var sawSSE = false
        var bufferedJSON = ""
        var lastModel = fallbackModel
        var lastUsage: TokenUsage?
        var lastFinishReason: String?
        do {
            for try await line in bytes.lines {
                let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)
                if trimmed.isEmpty || trimmed.hasPrefix(":") {
                    continue
                }
                guard trimmed.hasPrefix("data:") else {
                    bufferedJSON += line + "\n"
                    continue
                }
                sawSSE = true
                let payload = trimmed.dropFirst("data:".count).trimmingCharacters(in: .whitespaces)
                if payload == "[DONE]" {
                    break
                }
                guard let data = payload.data(using: .utf8),
                      let chunk = try? JSONDecoder().decode(OpenAIStreamChunkDTO.self, from: data),
                      let choice = chunk.choices?.first
                else { continue }
                if let reported = chunk.model, !reported.isEmpty {
                    lastModel = reported
                }
                if let usage = chunk.usage {
                    lastUsage = TokenUsage(
                        promptTokens: usage.promptTokens ?? 0,
                        completionTokens: usage.completionTokens ?? 0,
                        totalTokens: usage.totalTokens ?? 0
                    )
                }
                if let reason = choice.finishReason {
                    lastFinishReason = reason
                }
                let delta = choice.delta ?? choice.message
                if let text = delta?.content, !text.isEmpty {
                    continuation.yield(.textDelta(text))
                }
                for toolDelta in delta?.toolCalls ?? [] {
                    accumulator.apply(toolDelta)
                }
            }
            if !sawSSE, !bufferedJSON.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
               let data = bufferedJSON.data(using: .utf8),
               let chunk = try? JSONDecoder().decode(OpenAIStreamChunkDTO.self, from: data),
               let choice = chunk.choices?.first
            {
                if let reported = chunk.model, !reported.isEmpty {
                    lastModel = reported
                }
                if let usage = chunk.usage {
                    lastUsage = TokenUsage(
                        promptTokens: usage.promptTokens ?? 0,
                        completionTokens: usage.completionTokens ?? 0,
                        totalTokens: usage.totalTokens ?? 0
                    )
                }
                lastFinishReason = choice.finishReason ?? lastFinishReason
                let delta = choice.delta ?? choice.message
                if let text = delta?.content, !text.isEmpty {
                    continuation.yield(.textDelta(text))
                }
                for toolDelta in delta?.toolCalls ?? [] {
                    accumulator.apply(toolDelta)
                }
            }
        } catch is CancellationError {
            continuation.finish()
            return
        } catch {
            continuation.yield(.error("Chat stream failed: \(error.localizedDescription)"))
            continuation.finish()
            return
        }
        for call in accumulator.finishedCalls() {
            continuation.yield(.toolCall(call))
        }
        continuation.yield(.done(ResponseMetadata(model: lastModel, usage: lastUsage, finishReason: lastFinishReason)))
        continuation.finish()
    }
}
