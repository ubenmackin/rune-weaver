    /// - Parameter role: Core conversation role.
    /// - Returns: Wire role string.
    static func string(for role: Message.Role) -> String {
        switch role {
        case .system: "system"
        case .user: "user"
        case .assistant: "assistant"
        case .tool: "tool"
        }
    }
}

/// Normalizes a configured server URL to its `/v1` API root.
/// - Parameter raw: Configured URL, with or without a `/v1` suffix.
/// - Returns: Base URL without a trailing slash, ending in `/v1`.
func openAIBaseURL(from raw: String) -> String {
    var trimmed = raw
    while trimmed.hasSuffix("/") {
        trimmed.removeLast()
    }
    if trimmed.hasSuffix("/v1") {
        return trimmed
    }
    return trimmed + "/v1"
}

