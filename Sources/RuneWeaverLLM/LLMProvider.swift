/// Accumulates streamed tool-call fragments into whole calls.
struct OpenAIToolCallAccumulator: Sendable {
    /// Buffered state per tool-call index.
    var buffers: [Int: Buffer] = [:]

    /// Buffered fragments for one tool call.
    struct Buffer: Sendable {
        /// Server-assigned call identifier.
        var id: String = ""
        /// Tool name.
        var name: String = ""
        /// Concatenated arguments JSON.
        var arguments: String = ""
    }

    /// Applies one streamed delta.
    /// - Parameter delta: Tool-call delta from the server.
    mutating func apply(_ delta: OpenAIToolCallDeltaDTO) {
        let index = delta.index ?? 0
        var buffer = buffers[index] ?? Buffer()
        if let id = delta.id, !id.isEmpty {
            buffer.id = id
        }
        if let name = delta.function?.name, !name.isEmpty {
            buffer.name += name
        }
        if let arguments = delta.function?.arguments {
            buffer.arguments += arguments
        }
        buffers[index] = buffer
    }

    /// Finished calls ordered by index, dropping empties.
    /// - Returns: Reassembled tool calls.
    func finishedCalls() -> [ToolCall] {
        buffers
            .sorted { $0.key < $1.key }
            .map { entry in
                ToolCall(
                    id: entry.value.id.isEmpty ? "call_\(entry.key)" : entry.value.id,
                    name: entry.value.name,
                    argumentsJSON: entry.value.arguments.isEmpty ? "{}" : entry.value.arguments
                )
            }
            .filter { !$0.name.isEmpty }
    }
}

/// Accumulates split Responses tool-call fragments into whole calls.
struct OpenAIResponsesToolCallAccumulator: Sendable {
    /// Buffered state per call key.
    var buffers: [String: Buffer] = [:]
    /// First-seen key order for deterministic emission.
    var order: [String] = []

    /// Buffered fragments for one call.
    struct Buffer: Sendable {
        /// Call identifier reported to the router.
        var callId: String = ""
        /// Tool name.
        var name: String = ""
        /// Concatenated arguments JSON.
        var arguments: String = ""
    }

    /// Number of buffered calls.
    var count: Int {
        order.count
    }

    /// Ingests one stream event, buffering tool-call fragments.
    mutating func ingest(_ event: OpenAIResponsesStreamEventDTO, nextIndex: Int) {
        guard let type = event.type else { return }
        if type == "response.function_call_arguments.delta" {
            let key = event.itemId ?? event.callId ?? "call_\(nextIndex)"
            ensure(key: key, fallbackId: event.callId)
            if let delta = event.delta ?? event.arguments, var buffer = buffers[key] {
                buffer.arguments += delta
                buffers[key] = buffer
            }
            if let name = event.name, !name.isEmpty {
                appendName(name, for: key)
            }
            return
        }
        if type == "response.function_call_arguments.done" {
            let key = event.itemId ?? event.callId ?? "call_\(nextIndex)"
            ensure(key: key, fallbackId: event.callId)
            if let name = event.name, !name.isEmpty {
                buffers[key]?.name = name
            }
            if let callId = event.callId, !callId.isEmpty {
                buffers[key]?.callId = callId
            }
            let args = event.arguments ?? event.delta ?? ""
            if !args.isEmpty {
                buffers[key]?.arguments = args
            }
            return
        }
        guard let call = OpenAISSEPump.responsesToolCall(from: event, nextIndex: nextIndex) else { return }
        let key = event.itemId ?? event.item?.id ?? call.id
        ensure(key: key, fallbackId: call.id)
        if !call.name.isEmpty {
            if buffers[key]?.name.isEmpty ?? true {
                buffers[key]?.name = call.name
            } else if buffers[key]?.name != call.name, var buffer = buffers[key] {
                buffer.name += call.name
                buffers[key] = buffer
            }
        }
        let explicitCallId = event.item?.callId ?? event.callId
        if let explicitCallId, !explicitCallId.isEmpty, buffers[key]?.callId.isEmpty ?? false {
            buffers[key]?.callId = explicitCallId
        }
        if call.argumentsJSON != "{}" {
            if buffers[key]?.arguments.isEmpty ?? true {
                buffers[key]?.arguments = call.argumentsJSON
            } else if (buffers[key]?.arguments.count ?? 0) < call.argumentsJSON.count {
                buffers[key]?.arguments = call.argumentsJSON
            }
        }
    }

    /// Finished calls in first-seen order, dropping empties.
    /// - Returns: Reassembled tool calls.
    func finishedCalls() -> [ToolCall] {
        order.compactMap { key in
            guard let buffer = buffers[key], !buffer.name.isEmpty else { return nil }
            return ToolCall(
                id: buffer.callId.isEmpty ? key : buffer.callId,
                name: buffer.name,
                argumentsJSON: buffer.arguments.isEmpty ? "{}" : buffer.arguments
            )
        }
    }

    /// Ensures a buffer exists for the given key.
    private mutating func ensure(key: String, fallbackId: String?) {
        if buffers[key] == nil {
            buffers[key] = Buffer(callId: fallbackId ?? key)
            order.append(key)
        } else if let fallbackId, !fallbackId.isEmpty, buffers[key]?.callId.isEmpty ?? false {
            buffers[key]?.callId = fallbackId
        }
    }

    /// Appends a name fragment for the given key.
    private mutating func appendName(_ name: String, for key: String) {
        if buffers[key]?.name.isEmpty ?? true {
            buffers[key]?.name = name
        } else if var buffer = buffers[key] {
            buffer.name += name
            buffers[key] = buffer
        }
    }
}

/// Best-effort sticky slot hint for llama.cpp prompt-cache reuse.
public enum LlamaCppSlot: Sendable {
    /// Derives a best-effort slot for one chat session.
    /// Nil when no session is set so the server auto-assigns. The hash spreads
    /// sessions (FNV-1a over UTF-8) but cannot isolate them: hash collisions and
    /// pigeonhole overlap share a slot and evict each other's KV prefix, so treat
    /// pinning as a cache hint rather than isolation. The pool size stays an
    /// explicit caller argument with no fallback because any hardcoded count
    /// risks an out-of-range id on servers started with a smaller `--parallel`;
    /// pass the configured provider pool so small servers keep auto-assignment.
    public static func slotID(forSessionID sessionID: String?, slotCount: Int) -> Int? {
        guard let sessionID else { return nil }
        // Trim once and hash the trimmed form so padded and bare identifiers
        // share one slot; hashing the raw string would scatter one session
        // across slots and defeat prefix reuse.
        let trimmed = sessionID.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else {
            return nil
        }
        guard slotCount > 0 else { return nil }
        var hash: UInt64 = 14_695_981_039_346_656_037
        for byte in trimmed.utf8 {
            hash ^= UInt64(byte)
            hash &*= 1_099_511_628_211
        }
        return Int(hash % UInt64(slotCount))
    }

    /// Derives a best-effort slot for one chat session UUID.
    /// Same collision caveat as above; nil lets the server auto-assign. The pool
    /// stays explicit here as well so UUID callers cannot inherit a stale default.
    public static func slotID(forSession session: UUID?, slotCount: Int) -> Int? {
        guard let session else { return nil }
        return slotID(forSessionID: session.uuidString, slotCount: slotCount)
    }
}

/// Minimal shared client for OpenAI-compatible backends.
struct OpenAICompatibleHTTPClient: Sendable {
    /// API root ending in `/v1` (no trailing slash).
    let baseURL: String
    /// Effective base URL used for requests, rewritten to an RFC 1918 private IP when needed under ATS.
    let targetBaseURL: String
    /// Preserved Host header when targetBaseURL was rewritten from a multi-label local domain.
    let targetHostHeader: String?
    /// Bearer token, if the endpoint requires auth.
    let apiKey: String?
    /// Model identifier sent with every request.
    let model: String
    /// Request style selecting the wire endpoint and SSE shape.
    let apiStyle: APIStyle
    /// Chat session identifier sent as `x-opencode-session`, when set.
    let sessionID: String?
    /// llama.cpp-only prompt-cache hint; nil omits the key so cloud providers are unaffected.
    let cachePrompt: Bool?
    /// llama.cpp-only sticky slot; nil omits the key so the server auto-assigns.
    let slotID: Int?
    /// User-Agent sent on every request. Single-sourced through
    /// `RuneWeaverVersion` so providers, tools, and health cannot drift.
    static var userAgent: String {
        RuneWeaverVersion.userAgent
    }

    /// Creates a client.
    init(baseURL: String, apiKey: String? = nil, model: String, apiStyle: APIStyle = .chatCompletions, sessionID: String? = nil, cachePrompt: Bool? = nil, slotID: Int? = nil) {
        let normalized = openAIBaseURL(from: baseURL)
        self.baseURL = normalized
        self.apiKey = apiKey
        self.model = model
        self.apiStyle = apiStyle
        self.sessionID = sessionID
        self.cachePrompt = cachePrompt
        self.slotID = slotID
        // Intent: Resolve multi-label cleartext HTTP LAN hostnames (e.g.
        // http://nas.int.example.com:11434/v1) to their RFC 1918 / RFC 4193 private IP addresses
        // once at client initialization time.
        if let parsed = URL(string: normalized) {
            let target = LocalNetworking.resolvedLocalTarget(for: parsed)
            self.targetBaseURL = target.url.absoluteString
            self.targetHostHeader = target.originalHost
        } else {
            self.targetBaseURL = normalized
            self.targetHostHeader = nil
        }
    }

    /// Builds an authorized JSON request.
    func makeRequest(path: String, body: Data, timeout: TimeInterval = 120) -> URLRequest? {
        guard let url = URL(string: targetBaseURL + path) else { return nil }
        var request = URLRequest(url: url, timeoutInterval: timeout)
        request.httpMethod = "POST"
        request.setValue("application/json", forHTTPHeaderField: "Content-Type")
        if let apiKey, !apiKey.isEmpty {
            request.setValue("Bearer \(apiKey)", forHTTPHeaderField: "Authorization")
        }
        if let targetHostHeader {
            request.setValue(targetHostHeader, forHTTPHeaderField: "Host")
        }
        request.setValue(Self.userAgent, forHTTPHeaderField: "User-Agent")
        if let sessionID, !sessionID.isEmpty {
            request.setValue(sessionID, forHTTPHeaderField: "x-opencode-session")
        }
        request.httpBody = body
        return request
    }

    /// Streams chunks through a shared request and pump pipeline.
    func makeStreamingChunks(
        path: String,
        label: String,
        makeBody: () throws -> Data,
        pump: @Sendable @escaping (
            URLSession.AsyncBytes,
            String,
            AsyncStream<LLMResponseChunk>.Continuation
        ) async -> Void
    ) -> AsyncStream<LLMResponseChunk> {
        let body: Data
        do {
            body = try makeBody()
        } catch {
            let message: String = if let providerError = error as? LLMProviderError,
                                     case let .invalidResponse(detail) = providerError
            {
                detail
            } else {
                error.localizedDescription
            }
            return AsyncStream { continuation in
                continuation.yield(.error(message))
                continuation.finish()
            }
        }
        guard let request = makeRequest(path: path, body: body) else {
            let base = baseURL
            let style = label.lowercased()
            return AsyncStream { continuation in
                continuation.yield(.error("Malformed \(style) URL: \(base)"))
                continuation.finish()
            }
        }
        let clientModel = model
        let clientBase = baseURL
        return AsyncStream { continuation in
            let task = Task {
                do {
                    let (bytes, response) = try await URLSession.shared.bytes(for: request)
                    guard let http = response as? HTTPURLResponse else {
                        continuation.yield(.error("No HTTP response from \(clientBase)"))
                        continuation.finish()
                        return
                    }
                    guard (200 ..< 300).contains(http.statusCode) else {
                        let detail = await OpenAISSEPump.responseDetail(from: bytes)
                        continuation.yield(.error("\(label) request failed (\(http.statusCode)): \(detail)"))
                        continuation.finish()
                        return
                    }
                    await pump(bytes, clientModel, continuation)
                } catch is CancellationError {
                    continuation.finish()
                } catch {
                    let message = if let urlError = error as? URLError, urlError.code == .appTransportSecurityRequiresSecureConnection {
                        "\(label) cleartext HTTP was blocked by macOS App Transport Security. " +
                            "For local endpoints, use an RFC 1918 private IP address, a .local domain, or HTTPS."
                    } else {
                        "\(label) stream failed: \(error.localizedDescription)"
                    }
                    continuation.yield(.error(message))
                    continuation.finish()
                }
            }
            continuation.onTermination = { @Sendable _ in task.cancel() }
        }
    }

    /// Streams chat chunks for the given history and tools.
    func streamChunks(messages: [Message], tools: [ToolDefinition]) -> AsyncStream<LLMResponseChunk> {
        if apiStyle == .responses {
            return streamResponsesChunks(messages: messages, tools: tools)
        }
        let cacheHint = cachePrompt
        let slotHint = slotID
        return makeStreamingChunks(
            path: "/chat/completions",
            label: "Chat",
            makeBody: { try openAIChatRequestBody(model: model, messages: messages, tools: tools, stream: true, cachePrompt: cacheHint, slotID: slotHint) },
            pump: OpenAISSEPump.pumpSSE
        )
    }

    /// Streams chunks via the Responses API for the given history and tools.
    /// Forwards the same prefix hints as the chat wire so llama.cpp keeps the
    /// cached system prompt and sticky slot on both endpoints.
    func streamResponsesChunks(messages: [Message], tools: [ToolDefinition]) -> AsyncStream<LLMResponseChunk> {
        let cacheHint = cachePrompt
        let slotHint = slotID
        let responsesBody: () throws -> Data = {
            try openAIResponsesRequestBody(
                model: model,
                messages: messages,
                tools: tools,
                stream: true,
                cachePrompt: cacheHint,
                slotID: slotHint
            )
        }
        return makeStreamingChunks(
            path: "/responses",
            label: "Responses",
            makeBody: responsesBody,
            pump: OpenAISSEPump.pumpResponsesSSE
        )
    }

    /// Requests embeddings for the given texts.
    /// - Parameter texts: Texts to embed.
    /// - Returns: One vector per input text, in order.
    func requestEmbeddings(texts: [String]) async throws -> [[Float]] {
        let payload: [String: Any] = ["model": model, "input": texts]
        let body = (try? JSONSerialization.data(withJSONObject: payload, options: [.sortedKeys])) ?? Data()
        guard let request = makeRequest(path: "/embeddings", body: body, timeout: 60) else {
            throw LLMProviderError.invalidResponse("Malformed embeddings URL: \(baseURL)")
        }
        let (data, response): (Data, URLResponse)
        do {
            (data, response) = try await URLSession.shared.data(for: request)
        } catch {
            if let urlError = error as? URLError, urlError.code == .appTransportSecurityRequiresSecureConnection {
                throw LLMProviderError.unavailable(
                    "Embeddings cleartext HTTP was blocked by macOS App Transport Security. " +
                        "For local endpoints, use an RFC 1918 private IP address, a .local domain, or HTTPS."
                )
            }
            throw LLMProviderError.unavailable("Embeddings request failed: \(error.localizedDescription)")
        }
        guard let http = response as? HTTPURLResponse else {
            throw LLMProviderError.invalidResponse("No HTTP response from \(baseURL)")
        }
        guard (200 ..< 300).contains(http.statusCode) else {
            let detail = String(data: data, encoding: .utf8) ?? ""
            if http.statusCode == 404 {
                throw LLMProviderError.embeddingsUnsupported("No embeddings endpoint at \(baseURL): \(detail)")
            }
            throw LLMProviderError.requestFailed(statusCode: http.statusCode, message: detail)
        }
        do {
            let decoded = try JSONDecoder().decode(OpenAIEmbeddingsResponseDTO.self, from: data)
            return decoded.data.sorted { $0.index < $1.index }.map(\.embedding)
        } catch {
            throw LLMProviderError.invalidResponse("Could not decode embeddings: \(error.localizedDescription)")
        }
    }

    /// Probes `GET <base>/models` without throwing.
    /// - Returns: True when the server answers with 2xx.
    func ping() async -> Bool {
        guard let url = URL(string: targetBaseURL + "/models") else { return false }
        var request = URLRequest(url: url, timeoutInterval: 3)
        request.httpMethod = "GET"
        if let apiKey, !apiKey.isEmpty {
            request.setValue("Bearer \(apiKey)", forHTTPHeaderField: "Authorization")
        }
        if let targetHostHeader {
            request.setValue(targetHostHeader, forHTTPHeaderField: "Host")
        }
        request.setValue(Self.userAgent, forHTTPHeaderField: "User-Agent")
        if let sessionID, !sessionID.isEmpty {
            request.setValue(sessionID, forHTTPHeaderField: "x-opencode-session")
        }
        do {
            let (_, response) = try await URLSession.shared.data(for: request)
            guard let http = response as? HTTPURLResponse else { return false }
            return (200 ..< 300).contains(http.statusCode)
        } catch {
            return false
        }
    }
}

/// Pumps SSE byte streams into chunk events.
enum OpenAISSEPump {
    /// Reads a short error preview from an errored byte stream.
    /// - Parameter bytes: Response byte stream.
    /// - Returns: Decoded preview, or a placeholder.
    static func responseDetail(from bytes: URLSession.AsyncBytes) async -> String {
        var preview = ""
        do {
            for try await line in bytes.lines {
                preview += line
                if preview.count > 500 {
                    break
                }
            }
        } catch {
            return "unreadable error body"
        }
        let trimmed = preview.trimmingCharacters(in: .whitespacesAndNewlines)
        return trimmed.isEmpty ? "empty error body" : String(trimmed.prefix(500))
    }

    /// Applies one decoded chat SSE chunk to streaming state.
    static func ingestChatChunk(
        _ chunk: OpenAIStreamChunkDTO,
        lastModel: inout String,
        lastUsage: inout TokenUsage?,
        lastFinishReason: inout String?,
        toolAccumulator: inout OpenAIToolCallAccumulator
    ) -> String? {
        if let reported = chunk.model, !reported.isEmpty {
            lastModel = reported
        }
        if let usage = chunk.usage {
            let prompt = usage.promptTokens ?? 0
            let completion = usage.completionTokens ?? 0
            let total = usage.totalTokens ?? (prompt + completion)
            let cached = usage.effectiveCachedTokens
            lastUsage = TokenUsage(
                promptTokens: prompt,
                completionTokens: completion,
                totalTokens: total,
                cachedTokens: cached
            )
            // Surface prefix reuse where the server reports it: a growing cached
            // count beside a stable prompt count proves the leading bytes (system
            // prompt plus tools plus early history) hit the KV cache instead of
            // re-evaluating. Missing fields stay silent to preserve current behavior.
            if let cached {
                RuneWeaverLog.server.info("Chat usage: prompt \(prompt) tokens (\(cached) cached)")
            }
        }
        guard let choice = chunk.choices?.first else { return nil }
        if let reason = choice.finishReason {
            lastFinishReason = reason
        }
        let delta = choice.delta ?? choice.message
        for toolDelta in delta?.toolCalls ?? [] {
            toolAccumulator.apply(toolDelta)
        }
        if let text = delta?.content, !text.isEmpty {
            return text
        }
        return nil
    }

    /// Pumps SSE lines into chunk events.
    static func pumpSSE(
        bytes: URLSession.AsyncBytes,
        fallbackModel: String,
        continuation: AsyncStream<LLMResponseChunk>.Continuation
    ) async {
        var accumulator = OpenAIToolCallAccumulator()
        var sawSSE = false
        var bufferedJSON = ""
        var lastModel = fallbackModel
        var lastUsage: TokenUsage?
        var lastFinishReason: String?
        do {
            for try await line in bytes.lines {
                let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)
                if trimmed.isEmpty || trimmed.hasPrefix(":") {
                    continue
                }
                guard trimmed.hasPrefix("data:") else {
                    bufferedJSON += line + "\n"
                    continue
                }
                sawSSE = true
                let payload = trimmed.dropFirst("data:".count).trimmingCharacters(in: .whitespaces)
                if payload == "[DONE]" {
                    break
                }
                guard let data = payload.data(using: .utf8),
                      let chunk = try? JSONDecoder().decode(OpenAIStreamChunkDTO.self, from: data)
                else { continue }
                if let text = ingestChatChunk(
                    chunk,
                    lastModel: &lastModel,
                    lastUsage: &lastUsage,
                    lastFinishReason: &lastFinishReason,
                    toolAccumulator: &accumulator
                ) {
                    continuation.yield(.textDelta(text))
                }
            }
            if !sawSSE, !bufferedJSON.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
               let data = bufferedJSON.data(using: .utf8),
               let chunk = try? JSONDecoder().decode(OpenAIStreamChunkDTO.self, from: data)
            {
                if let text = ingestChatChunk(
                    chunk,
                    lastModel: &lastModel,
                    lastUsage: &lastUsage,
                    lastFinishReason: &lastFinishReason,
                    toolAccumulator: &accumulator
                ) {
                    continuation.yield(.textDelta(text))
                }
            }
        } catch is CancellationError {
            continuation.finish()
            return
        } catch {
            continuation.yield(.error("Chat stream failed: \(error.localizedDescription)"))
            continuation.finish()
            return
        }
        for call in accumulator.finishedCalls() {
            continuation.yield(.toolCall(call))
        }
        continuation.yield(.done(ResponseMetadata(model: lastModel, usage: lastUsage, finishReason: lastFinishReason)))
        continuation.finish()
    }

    /// One outcome of a Responses stream event.
    enum ResponsesEventEffect {
        /// Emit incremental text.
        case textDelta(String)
        /// Record completion details.
        case completed(model: String?, usage: TokenUsage?)
        /// Fail the stream with a message.
        case error(String)
        /// Buffer a tool call for the end of the stream.
        case toolCall(ToolCall)
        /// No observable effect.
        case ignored
    }

    /// Maps one Responses event to its stream effect.
    static func effect(for event: OpenAIResponsesStreamEventDTO, nextIndex: Int) -> ResponsesEventEffect {
        guard let type = event.type else {
            if let message = event.errorMessage {
                return .error(message)
            }
            return .ignored
        }
        switch type {
        case "response.output_text.delta":
            guard let delta = event.delta, !delta.isEmpty else {
                return .ignored
            }
            return .textDelta(delta)
        case "response.completed":
            let model = event.response?.model.flatMap { $0.isEmpty ? nil : $0 }
            return .completed(model: model, usage: responsesUsage(from: event.response?.usage))
        case "error", "response.failed", "response.error":
            return .error(event.errorMessage ?? "unknown error")
        default:
            if let call = responsesToolCall(from: event, nextIndex: nextIndex) {
                return .toolCall(call)
            }
            return .ignored
        }
    }

    /// Extracts a tool call from a function-call event.
    static func responsesToolCall(from event: OpenAIResponsesStreamEventDTO, nextIndex: Int) -> ToolCall? {
        guard let type = event.type else {
            return nil
        }
        if let item = event.item, item.type == "function_call" {
            let name = item.name ?? event.name ?? ""
            guard !name.isEmpty else {
                return nil
            }
            let rawArguments = item.arguments ?? event.arguments ?? ""
            let callId = item.callId ?? item.id ?? event.callId ?? "call_\(nextIndex)"
            return ToolCall(id: callId, name: name, argumentsJSON: rawArguments.isEmpty ? "{}" : rawArguments)
        }
        if type.contains("function_call") {
            guard let name = event.name, !name.isEmpty else {
                return nil
            }
            let rawArguments = event.arguments ?? ""
            let callId = event.callId ?? "call_\(nextIndex)"
            return ToolCall(id: callId, name: name, argumentsJSON: rawArguments.isEmpty ? "{}" : rawArguments)
        }
        return nil
    }

    /// Converts a Responses usage block to token accounting.
    static func responsesUsage(from dto: OpenAIResponsesUsageDTO?) -> TokenUsage? {
        guard let dto else {
            return nil
        }
        let prompt = dto.inputTokens ?? 0
        let completion = dto.outputTokens ?? 0
        let cached = dto.effectiveCachedTokens
        let usage = TokenUsage(
            promptTokens: prompt,
            completionTokens: completion,
            totalTokens: dto.totalTokens ?? (prompt + completion),
            cachedTokens: cached
        )
        // Same prefix-reuse signal as the chat wire: log only when the server
        // reports a cache count so absent fields degrade to current behavior.
        if let cached {
            RuneWeaverLog.server.info("Responses usage: prompt \(prompt) tokens (\(cached) cached)")
        }
        return usage
    }

    /// Pumps Responses SSE lines into chunk events.
    static func pumpResponsesSSE(
        bytes: URLSession.AsyncBytes,
        fallbackModel: String,
        continuation: AsyncStream<LLMResponseChunk>.Continuation
    ) async {
        var lastModel = fallbackModel
        var lastUsage: TokenUsage?
        var accumulator = OpenAIResponsesToolCallAccumulator()
        do {
            for try await line in bytes.lines {
                let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)
                if trimmed.isEmpty || trimmed.hasPrefix(":") {
                    continue
                }
                guard trimmed.hasPrefix("data:") else {
                    continue
                }
                let payload = trimmed.dropFirst("data:".count).trimmingCharacters(in: .whitespaces)
                if payload == "[DONE]" {
                    break
                }
                guard let data = payload.data(using: .utf8),
                      let event = try? JSONDecoder().decode(OpenAIResponsesStreamEventDTO.self, from: data)
                else { continue }
                let nextIndex = accumulator.count
                accumulator.ingest(event, nextIndex: nextIndex)
                switch effect(for: event, nextIndex: nextIndex) {
                case let .textDelta(delta):
                    continuation.yield(.textDelta(delta))
                case let .completed(model, usage):
                    if let model {
                        lastModel = model
                    }
                    if let usage {
                        lastUsage = usage
                    }
                case let .error(message):
                    continuation.yield(.error(message))
                    continuation.finish()
                    return
                case .toolCall:
                    // Buffered in the accumulator and emitted at the end,
                    // once delta fragments have reassembled.
                    continue
                case .ignored:
                    continue
                }
            }
        } catch is CancellationError {
            continuation.finish()
            return
        } catch {
            continuation.yield(.error("Responses stream failed: \(error.localizedDescription)"))
            continuation.finish()
            return
        }
        for call in accumulator.finishedCalls() {
            continuation.yield(.toolCall(call))
        }
        continuation.yield(.done(ResponseMetadata(model: lastModel, usage: lastUsage, finishReason: nil)))
        continuation.finish()
    }
}
